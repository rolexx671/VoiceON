#!/bin/bash
set -euo pipefail

if [ "$#" -gt 0 ] && [ "$1" != "--help" ] && [ "$1" != "-h" ]; then
    printf '%s\n' 'Этот скрипт показывает инструкцию по установке VoiceON и не принимает параметров.' >&2
    exit 1
fi

cat <<'INSTRUCTIONS'
Установка VoiceON

1. Скачайте файл VoiceON.dmg со страницы:
   https://github.com/rolexx671/VoiceON/releases/latest
2. Откройте VoiceON.dmg и перетащите VoiceON в папку «Программы».
3. Запустите VoiceON из папки «Программы».
4. Разрешите доступ к микрофону и универсальному доступу в настройках macOS.

VoiceON работает на Mac с Apple Silicon (M1 и новее), macOS 13 и новее.
Русский язык и многоязычная модель распознавания выбраны по умолчанию.
Модель и движок входят в приложение. Homebrew для использования не нужен.
Настройки и история хранятся в ~/.config/voiceon.

Если macOS блокирует первое открытие:
откройте «Системные настройки» → «Конфиденциальность и безопасность»
и разрешите запуск VoiceON кнопкой «Всё равно открыть».
INSTRUCTIONS
